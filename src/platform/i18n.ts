export type Translator = (key: MessageKey, values?: Record<string, string | number>) => string;

export function resolveUiLocale(preference: InterfaceLocale, browserLanguage = 'en'): UiLocale {
  if (preference === 'zh_CN' || preference === 'en') return preference;
  return browserLanguage.toLowerCase().startsWith('zh') ? 'zh_CN' : 'en';
}

export function createTranslator(locale: UiLocale): Translator {
  const messages = locale === 'zh_CN' ? ZH : EN;
  return (key, values = {}) => Object.entries(values).reduce(
    (message, [name, value]) => message.replaceAll(`{${name}}`, String(value)),
    messages[key],
  );
}
